CREATE TABLE insurance_coverage (
    coverage_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id INTEGER,
    treatment_id INTEGER,
    coverage_percentage NUMERIC(5,2),
    maximum_amount NUMERIC(12,2),
    CONSTRAINT fk_insurance_coverage_policy
        FOREIGN KEY (policy_id) REFERENCES insurance_policy(policy_id),
    CONSTRAINT fk_insurance_coverage_treatment
        FOREIGN KEY (treatment_id) REFERENCES treatment(treatment_id)
);

CREATE TABLE consultation_note (
    note_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id INTEGER,
    note_content VARCHAR(2000),
    created_at TIMESTAMP,
    CONSTRAINT fk_consultation_note_appointment
        FOREIGN KEY (appointment_id) REFERENCES appointment(appointment_id)
);

CREATE TABLE insurance_claim (
    claim_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id INTEGER,
    policy_id INTEGER,
    claim_date DATE,
    claim_amount NUMERIC(12,2),
    approved VARCHAR(100),
    amount NUMERIC(12,2),
    status VARCHAR(100),
    CONSTRAINT fk_insurance_claim_invoice
        FOREIGN KEY (invoice_id) REFERENCES invoice(invoice_id),
    CONSTRAINT fk_insurance_claim_policy
        FOREIGN KEY (policy_id) REFERENCES insurance_policy(policy_id)
);


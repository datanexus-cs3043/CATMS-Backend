CREATE TABLE insurance_policy (
    policy_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INTEGER,
    provider_id INTEGER,
    policy_number INTEGER,
    start_date DATE,
    end_date DATE,
    status VARCHAR(100),
    CONSTRAINT fk_insurance_policy_patient
        FOREIGN KEY (patient_id) REFERENCES patient(patient_id),
    CONSTRAINT fk_insurance_policy_provider
        FOREIGN KEY (provider_id) REFERENCES insurance_provider(provider_id)
);

CREATE TABLE treatment_category (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(150),
    description VARCHAR(500)
);

CREATE TABLE treatment (
    treatment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id INTEGER,
    service_code VARCHAR(100) UNIQUE,
    treatment_name VARCHAR(200),
    standard_price NUMERIC(12,2),
    CONSTRAINT fk_treatment_category
        FOREIGN KEY (category_id) REFERENCES treatment_category(category_id)
);

CREATE TABLE doctor (
    doctor_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_id INTEGER,
    doctor_name VARCHAR(200),
    doctor_license_number VARCHAR(100),
    CONSTRAINT fk_doctor_staff
        FOREIGN KEY (staff_id) REFERENCES staff(staff_id)
);


-- MedSync CATMS - Database DDL (02_tables.sql)
-- Target: PostgreSQL 16+ (Neon Cloud / Local)
-- 20 Normalized Relational Entities in strict topological dependency sequence

-- ============================================================================
-- 1. Core Users & System Authentication (Sithuka)
-- ============================================================================

-- 1. User accounts
CREATE TABLE "user" (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    contact_details VARCHAR(255),
    email VARCHAR(255) NOT NULL,
    username VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL
);

-- 2. Clinic branches (manager_staff_id FK deferred to 03_constraints.sql to prevent circular dependency)
CREATE TABLE branch (
    branch_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_name VARCHAR(150) NOT NULL,
    location VARCHAR(255) NOT NULL,
    contact_details VARCHAR(255),
    manager_staff_id INTEGER UNIQUE
);

-- 3. User login tracking / session audit
CREATE TABLE users_logins (
    users_logins_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES "user"(user_id),
    login_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_name VARCHAR(100) NOT NULL
);

-- 4. Staff members
CREATE TABLE staff (
    staff_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id INTEGER NOT NULL REFERENCES branch(branch_id),
    users_logins_id INTEGER REFERENCES users_logins(users_logins_id),
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    contact_details VARCHAR(255),
    email VARCHAR(255) NOT NULL,
    staff_type VARCHAR(100) NOT NULL,
    role VARCHAR(100) NOT NULL
);

-- ============================================================================
-- 2. Clinical Catalogues & Medical Staff (Nayanajith / Adithya)
-- ============================================================================

-- 5. Treatment categories (Nayanajith)
CREATE TABLE treatment_category (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(150) NOT NULL,
    description VARCHAR(500)
);

-- 6. Predefined treatment catalogue (Nayanajith)
CREATE TABLE treatment (
    treatment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id INTEGER NOT NULL REFERENCES treatment_category(category_id),
    service_code VARCHAR(50) NOT NULL UNIQUE,
    treatment_name VARCHAR(150) NOT NULL,
    standard_price NUMERIC(10, 2) NOT NULL
);

-- 7. Medical specialties catalogue (Adithya)
CREATE TABLE specialty (
    specialty_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    specialty_name VARCHAR(150) NOT NULL,
    description VARCHAR(500)
);

-- 8. Doctor extension (Nayanajith)
CREATE TABLE doctor (
    doctor_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_id INTEGER NOT NULL UNIQUE REFERENCES staff(staff_id),
    doctor_name VARCHAR(150) NOT NULL,
    doctor_license_number VARCHAR(100) NOT NULL UNIQUE
);

-- 9. Doctor specialties bridge table (Shashika)
CREATE TABLE doctor_specialty (
    doctor_id INTEGER NOT NULL REFERENCES doctor(doctor_id),
    specialty_id INTEGER NOT NULL REFERENCES specialty(specialty_id),
    PRIMARY KEY (doctor_id, specialty_id)
);

-- ============================================================================
-- 3. Patients & Insurance Management (Adithya / Nayanajith / Tharushi)
-- ============================================================================

-- 10. Insurance providers (Adithya)
CREATE TABLE insurance_provider (
    provider_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_name VARCHAR(200) NOT NULL UNIQUE,
    contact_details VARCHAR(255)
);

-- 11. Patients (Adithya)
CREATE TABLE patient (
    patient_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id INTEGER NOT NULL REFERENCES branch(branch_id),
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    date_of_birth DATE NOT NULL,
    gender VARCHAR(50) NOT NULL,
    patient_type VARCHAR(100),
    contact_details VARCHAR(255),
    email VARCHAR(255),
    address VARCHAR(500),
    user_id INTEGER NOT NULL REFERENCES user(user_id)
);

-- 12. Patient emergency contacts (Adithya)
CREATE TABLE emergency_contact (
    emergency_contact_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INTEGER NOT NULL REFERENCES patient(patient_id),
    contact_name VARCHAR(150) NOT NULL,
    relationship VARCHAR(100) NOT NULL,
    phone VARCHAR(50) NOT NULL
);

-- 13. Patient insurance policies (Nayanajith)
CREATE TABLE insurance_policy (
    policy_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INTEGER NOT NULL REFERENCES patient(patient_id),
    provider_id INTEGER NOT NULL REFERENCES insurance_provider(provider_id),
    policy_number INTEGER NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    status VARCHAR(100) NOT NULL
);

-- 14. Insurance coverage rules per policy and treatment (Tharushi)
CREATE TABLE insurance_coverage (
    coverage_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id INTEGER NOT NULL REFERENCES insurance_policy(policy_id),
    treatment_id INTEGER NOT NULL REFERENCES treatment(treatment_id),
    coverage_percentage NUMERIC(5, 2) NOT NULL,
    maximum_amount NUMERIC(10, 2) NOT NULL
);

-- ============================================================================
-- 4. Appointments & Consultations (Shashika / Tharushi)
-- ============================================================================

-- 15. Appointments with self-reference for rescheduling history (Shashika)
CREATE TABLE appointment (
    appointment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INTEGER NOT NULL REFERENCES patient(patient_id),
    doctor_id INTEGER NOT NULL REFERENCES doctor(doctor_id),
    branch_id INTEGER NOT NULL REFERENCES branch(branch_id),
    appointment_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    appointment_type VARCHAR(100) NOT NULL,
    created_by VARCHAR(150) NOT NULL,
    original_appointment_id INTEGER REFERENCES appointment(appointment_id),
    treatment_id INTEGER REFERENCES treatment(treatment_id)
);

-- 16. Consultation notes (Tharushi)
CREATE TABLE consultation_note (
    note_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id INTEGER NOT NULL REFERENCES appointment(appointment_id),
    note_content TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ============================================================================
-- 5. Invoicing, Payments & Claims (Shashika / Tharushi)
-- ============================================================================

-- 17. Invoices (Shashika)
CREATE TABLE invoice (
    invoice_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id INTEGER NOT NULL UNIQUE REFERENCES appointment(appointment_id),
    staff_id INTEGER NOT NULL REFERENCES staff(staff_id),
    invoice_date DATE NOT NULL,
    amount_paid NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    balance NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    status VARCHAR(100) NOT NULL
);

-- 18. Invoice items (Shashika)
CREATE TABLE invoice_item (
    invoice_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id INTEGER NOT NULL REFERENCES invoice(invoice_id),
    treatment_id INTEGER NOT NULL REFERENCES treatment(treatment_id),
    quantity INTEGER NOT NULL DEFAULT 1,
    unitprice NUMERIC(10, 2) NOT NULL,
    description VARCHAR(255)
);

-- 19. Doctor payments (Tharushi)
CREATE TABLE doctor_payment (
    doctor_payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id INTEGER NOT NULL REFERENCES doctor(doctor_id),
    appointment_id INTEGER NOT NULL REFERENCES appointment(appointment_id),
    invoice_item_id INTEGER REFERENCES invoice_item(invoice_item_id),
    date DATE NOT NULL,
    time TIME NOT NULL,
    doctor_payment NUMERIC(10, 2) NOT NULL
);

-- 20. Insurance claims (Tharushi)
CREATE TABLE insurance_claim (
    claim_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id INTEGER NOT NULL REFERENCES invoice(invoice_id),
    policy_id INTEGER NOT NULL REFERENCES insurance_policy(policy_id),
    claim_date DATE NOT NULL,
    claim_amount NUMERIC(10, 2) NOT NULL,
    approved_amount NUMERIC(10, 2) DEFAULT 0.00,
    status VARCHAR(100) NOT NULL
);

USE medsync;


CREATE TABLE "user" (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100),
    last_name VARCHAR(100),
    contact_details VARCHAR(255),
    email VARCHAR(255),
    username VARCHAR(100) UNIQUE,
    password VARCHAR(255)
);

CREATE TABLE branch (
    branch_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_name VARCHAR(150),
    location VARCHAR(255),
    contact_details VARCHAR(255),
    manager_staff_id INTEGER UNIQUE
);

CREATE TABLE users_logins (
    users_logins_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER,
    login_time TIMESTAMP,
    user_name VARCHAR(100),
    CONSTRAINT fk_users_logins_user
        FOREIGN KEY (user_id) REFERENCES "user"(user_id)
);

CREATE TABLE staff (
    staff_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id INTEGER,
    users_logins_id INTEGER,
    first_name VARCHAR(100),
    last_name VARCHAR(100),
    contact_details VARCHAR(255),
    email VARCHAR(255),
    staff_type VARCHAR(100),
    role VARCHAR(100),
    CONSTRAINT fk_staff_branch
        FOREIGN KEY (branch_id) REFERENCES branch(branch_id),
    CONSTRAINT fk_staff_users_logins
        FOREIGN KEY (users_logins_id) REFERENCES users_logins(users_logins_id)
);
